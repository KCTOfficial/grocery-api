<?php

declare(strict_types=1);

namespace GroceryRestable\OpenApi;

use GroceryRestable\Database\Schema\Column;
use GroceryRestable\Resource\ResolvedResource;
use GroceryRestable\Resource\Resource;

/**
 * Generates an OpenAPI 3.1 document describing every exposed resource.
 */
final class OpenApiGenerator
{
    /**
     * @param list<ResolvedResource> $resources
     * @param list<array<string, mixed>> $buckets
     * @param array<string, array<string, mixed>> $functions RPC functions (name => options)
     * @param array<string, mixed> $settings
     * @return array<string, mixed>
     */
    public function generate(array $resources, array $buckets, array $functions, array $settings, string $serverUrl): array
    {
        $spec = [
            'openapi' => '3.1.0',
            'info' => [
                'title' => (string) ($settings['app_name'] ?? 'Grocery Restable'),
                'description' => (string) ($settings['api_description'] ?? '') ?: 'REST API generated by Grocery Restable.',
                'version' => '1.0.0',
            ],
            'servers' => [['url' => $serverUrl]],
            'tags' => [],
            'paths' => [],
            'components' => [
                'securitySchemes' => [
                    'apiKey' => ['type' => 'apiKey', 'in' => 'header', 'name' => 'apikey'],
                    'bearer' => ['type' => 'http', 'scheme' => 'bearer', 'bearerFormat' => 'JWT or API key'],
                ],
                'parameters' => $this->commonParameters(),
                'schemas' => [
                    'Error' => [
                        'type' => 'object',
                        'properties' => [
                            'error' => [
                                'type' => 'object',
                                'properties' => [
                                    'code' => ['type' => 'string'],
                                    'message' => ['type' => 'string'],
                                    'details' => ['type' => 'object'],
                                ],
                            ],
                        ],
                    ],
                ],
                'responses' => [
                    'Error' => ['description' => 'Error', 'content' => ['application/json' => ['schema' => ['$ref' => '#/components/schemas/Error']]]],
                ],
            ],
        ];
        if (($settings['auth_mode'] ?? 'none') !== 'none') {
            $spec['security'] = [['apiKey' => []], ['bearer' => []]];
        }

        foreach ($resources as $ctx) {
            $this->addResource($spec, $ctx);
        }
        if ($buckets !== []) {
            $this->addStorage($spec, $buckets);
        }
        foreach ($functions as $name => $options) {
            $methods = $options['methods'] ?? ['POST'];
            $operation = [
                'tags' => ['rpc'],
                'summary' => (string) ($options['description'] ?? 'Call ' . $name),
                'operationId' => 'rpc_' . $name,
                'responses' => ['200' => ['description' => 'Function result'], 'default' => ['$ref' => '#/components/responses/Error']],
            ];
            foreach ($methods as $method) {
                $op = $operation;
                if (strtoupper($method) === 'POST') {
                    $op['requestBody'] = ['content' => ['application/json' => ['schema' => ['type' => 'object']]]];
                }
                $op['operationId'] .= '_' . strtolower($method);
                $spec['paths']['/rpc/' . $name][strtolower($method)] = $op;
            }
        }
        if ($functions !== []) {
            $spec['tags'][] = ['name' => 'rpc', 'description' => 'Remote procedures'];
        }

        return $spec;
    }

    /**
     * @param array<string, mixed> $spec
     */
    private function addResource(array &$spec, ResolvedResource $ctx): void
    {
        $resource = $ctx->resource;
        $table = $ctx->table;
        $name = $ctx->name();
        $schemaName = self::schemaName($name);
        $pk = $ctx->primaryKey();
        $tag = $name;

        $spec['tags'][] = ['name' => $tag, 'description' => $resource->getDescription() ?: $resource->getSubject()];

        // Output schema
        $properties = [];
        foreach ($resource->queryableColumns($table) as $column) {
            $properties[$column] = $this->columnSchema($table->columns[$column], $resource);
        }
        foreach ($resource->getRelations() as $relation) {
            $properties[$relation->name] = $relation->isBelongsTo()
                ? ['type' => ['object', 'null'], 'description' => 'Embedded ' . $relation->table . ' (select=' . $relation->name . '(*))']
                : ['type' => 'array', 'items' => ['type' => 'object'], 'description' => 'Embedded ' . $relation->table . ' (select=' . $relation->name . '(*))'];
        }
        $spec['components']['schemas'][$schemaName] = ['type' => 'object', 'properties' => $properties];

        // Input schema
        $input = [];
        $required = [];
        foreach ($resource->writableFields($table, 'create') as $field) {
            $relation = $resource->getRelation($field);
            if ($relation !== null) {
                $input[$field] = ['type' => 'array', 'items' => ['type' => ['integer', 'string']], 'description' => 'Ids of related ' . $relation->table];
                continue;
            }
            $schema = $this->columnSchema($table->columns[$field], $resource);
            if ($resource->getUpload($field) !== null) {
                $schema = ['type' => 'string', 'format' => 'binary', 'description' => 'File upload (multipart/form-data)'];
            }
            $input[$field] = $schema;
            if (in_array($field, $resource->getRequiredFields(), true) || ! $table->columns[$field]->isOptionalOnInsert()) {
                $required[] = $field;
            }
        }
        $spec['components']['schemas'][$schemaName . 'Input'] = array_filter(['type' => 'object', 'properties' => $input, 'required' => $required ?: null]);

        $ref = ['$ref' => '#/components/schemas/' . $schemaName];
        $inputRef = ['$ref' => '#/components/schemas/' . $schemaName . 'Input'];
        $error = ['$ref' => '#/components/responses/Error'];
        $body = [
            'required' => true,
            'content' => [
                'application/json' => ['schema' => $inputRef],
                'multipart/form-data' => ['schema' => $inputRef],
            ],
        ];
        $filterParams = [];
        foreach ($resource->queryableColumns($table) as $column) {
            $filterParams[] = [
                'name' => $column,
                'in' => 'query',
                'required' => false,
                'description' => 'Filter, e.g. `eq.value`, `gt.10`, `in.(a,b)`, `ilike.*text*`, `is.null`, `not.eq.value`',
                'schema' => ['type' => 'string'],
            ];
        }

        $collection = [];
        if ($resource->isEnabled('list')) {
            $collection['get'] = [
                'tags' => [$tag],
                'summary' => 'List ' . ($resource->getSubjectPlural() ?? $resource->getSubject()),
                'operationId' => 'list_' . $name,
                'parameters' => [
                    ...array_map(static fn (string $p): array => ['$ref' => '#/components/parameters/' . $p], ['select', 'order', 'limit', 'offset', 'page', 'per_page', 'q', 'count', 'format', 'or']),
                    ...$filterParams,
                ],
                'responses' => [
                    '200' => [
                        'description' => 'Rows. Headers: Content-Range, X-Total-Count (with count=exact).',
                        'content' => ['application/json' => ['schema' => ['type' => 'array', 'items' => $ref]], 'text/csv' => ['schema' => ['type' => 'string']]],
                    ],
                    'default' => $error,
                ],
            ];
        }
        if ($resource->isEnabled('create')) {
            $collection['post'] = [
                'tags' => [$tag],
                'summary' => 'Create ' . $resource->getSubject() . ' (an array creates many; Prefer: resolution=merge-duplicates upserts)',
                'operationId' => 'create_' . $name,
                'parameters' => [['$ref' => '#/components/parameters/select'], ['$ref' => '#/components/parameters/prefer']],
                'requestBody' => $body,
                'responses' => ['201' => ['description' => 'Created', 'content' => ['application/json' => ['schema' => $ref]]], 'default' => $error],
            ];
        }
        if ($pk !== null && $resource->isEnabled('update')) {
            $collection['patch'] = [
                'tags' => [$tag],
                'summary' => 'Update every ' . $resource->getSubject() . ' matching the filters',
                'operationId' => 'update_many_' . $name,
                'parameters' => $filterParams,
                'requestBody' => ['content' => ['application/json' => ['schema' => $inputRef]]],
                'responses' => ['200' => ['description' => 'Updated rows', 'content' => ['application/json' => ['schema' => ['type' => 'array', 'items' => $ref]]]], 'default' => $error],
            ];
        }
        if ($pk !== null && $resource->isEnabled('delete')) {
            $collection['delete'] = [
                'tags' => [$tag],
                'summary' => 'Delete every ' . $resource->getSubject() . ' matching the filters',
                'operationId' => 'delete_many_' . $name,
                'parameters' => $filterParams,
                'responses' => ['200' => ['description' => 'Deleted ids'], 'default' => $error],
            ];
        }
        if ($collection !== []) {
            $spec['paths']['/' . $name] = $collection;
        }

        if ($pk === null) {
            return;
        }

        $idParam = ['name' => 'id', 'in' => 'path', 'required' => true, 'schema' => $this->columnSchema($table->columns[$pk], $resource)];
        $item = ['parameters' => [$idParam]];
        if ($resource->isEnabled('read')) {
            $item['get'] = [
                'tags' => [$tag],
                'summary' => 'Get one ' . $resource->getSubject(),
                'operationId' => 'get_' . $name,
                'parameters' => [['$ref' => '#/components/parameters/select']],
                'responses' => ['200' => ['description' => 'Row', 'content' => ['application/json' => ['schema' => $ref]]], 'default' => $error],
            ];
        }
        if ($resource->isEnabled('update')) {
            foreach (['put' => 'Replace', 'patch' => 'Update'] as $method => $verb) {
                $item[$method] = [
                    'tags' => [$tag],
                    'summary' => $verb . ' ' . $resource->getSubject(),
                    'operationId' => $method . '_' . $name,
                    'requestBody' => $body,
                    'responses' => ['200' => ['description' => 'Updated row', 'content' => ['application/json' => ['schema' => $ref]]], 'default' => $error],
                ];
            }
        }
        if ($resource->isEnabled('delete')) {
            $item['delete'] = [
                'tags' => [$tag],
                'summary' => 'Delete ' . $resource->getSubject(),
                'operationId' => 'delete_' . $name,
                'responses' => ['204' => ['description' => 'Deleted'], 'default' => $error],
            ];
        }
        $spec['paths']['/' . $name . '/{id}'] = $item;

        if ($resource->isEnabled('clone')) {
            $spec['paths']['/' . $name . '/{id}/clone'] = [
                'parameters' => [$idParam],
                'post' => [
                    'tags' => [$tag],
                    'summary' => 'Clone ' . $resource->getSubject() . ' (body overrides fields)',
                    'operationId' => 'clone_' . $name,
                    'responses' => ['201' => ['description' => 'Created copy', 'content' => ['application/json' => ['schema' => $ref]]], 'default' => $error],
                ],
            ];
        }

        foreach ($resource->getUploads() as $field => $upload) {
            $spec['paths']['/' . $name . '/{id}/upload/' . $field] = [
                'parameters' => [$idParam],
                'post' => [
                    'tags' => [$tag],
                    'summary' => 'Upload ' . $resource->label($field) . ($upload->allowedTypes ? ' (' . $upload->allowedTypes . ')' : ''),
                    'operationId' => 'upload_' . $name . '_' . $field,
                    'requestBody' => ['required' => true, 'content' => ['multipart/form-data' => ['schema' => [
                        'type' => 'object', 'properties' => ['file' => ['type' => 'string', 'format' => 'binary']], 'required' => ['file'],
                    ]]]],
                    'responses' => ['200' => ['description' => 'Updated row', 'content' => ['application/json' => ['schema' => $ref]]], 'default' => $error],
                ],
                'delete' => [
                    'tags' => [$tag],
                    'summary' => 'Remove the ' . $resource->label($field) . ' file',
                    'operationId' => 'remove_upload_' . $name . '_' . $field,
                    'responses' => ['200' => ['description' => 'Updated row'], 'default' => $error],
                ],
            ];
            $spec['paths']['/' . $name . '/{id}/file/' . $field] = [
                'parameters' => [$idParam],
                'get' => [
                    'tags' => [$tag],
                    'summary' => 'Download the ' . $resource->label($field) . ' file',
                    'operationId' => 'download_' . $name . '_' . $field,
                    'responses' => ['200' => ['description' => 'File content'], 'default' => $error],
                ],
            ];
        }

        foreach ($resource->getRelations() as $relation) {
            if ($relation->isHasMany()) {
                continue;
            }
            $field = $relation->isBelongsTo() ? (string) $relation->field : $relation->name;
            $spec['paths']['/' . $name . '/_options/' . $field] = [
                'get' => [
                    'tags' => [$tag],
                    'summary' => 'Value / label options for ' . $resource->label($field),
                    'operationId' => 'options_' . $name . '_' . $field,
                    'parameters' => [['$ref' => '#/components/parameters/q'], ['$ref' => '#/components/parameters/limit']],
                    'responses' => ['200' => ['description' => 'Options', 'content' => ['application/json' => ['schema' => [
                        'type' => 'array',
                        'items' => ['type' => 'object', 'properties' => ['value' => [], 'label' => ['type' => 'string']]],
                    ]]]], 'default' => $error],
                ],
            ];
        }

        foreach ($resource->getActions() as $action => $definition) {
            $spec['paths']['/' . $name . '/{id}/actions/' . $action] = [
                'parameters' => [$idParam],
                'post' => [
                    'tags' => [$tag],
                    'summary' => 'Action: ' . $action,
                    'operationId' => 'action_' . $name . '_' . $action,
                    'requestBody' => ['content' => ['application/json' => ['schema' => ['type' => 'object']]]],
                    'responses' => ['200' => ['description' => 'Action result'], 'default' => $error],
                ],
            ];
        }
    }

    /**
     * @param array<string, mixed> $spec
     * @param list<array<string, mixed>> $buckets
     */
    private function addStorage(array &$spec, array $buckets): void
    {
        $spec['tags'][] = ['name' => 'storage', 'description' => 'File storage buckets: ' . implode(', ', array_column($buckets, 'name'))];
        $bucketParam = ['name' => 'bucket', 'in' => 'path', 'required' => true, 'schema' => ['type' => 'string', 'enum' => array_column($buckets, 'name')]];
        $pathParam = ['name' => 'path', 'in' => 'path', 'required' => true, 'schema' => ['type' => 'string'], 'description' => 'Object path, may contain "/"'];
        $error = ['$ref' => '#/components/responses/Error'];

        $spec['paths']['/storage'] = ['get' => ['tags' => ['storage'], 'summary' => 'List buckets', 'operationId' => 'storage_buckets', 'responses' => ['200' => ['description' => 'Buckets']]]];
        $spec['paths']['/storage/{bucket}'] = [
            'parameters' => [$bucketParam],
            'get' => [
                'tags' => ['storage'], 'summary' => 'List objects', 'operationId' => 'storage_list',
                'parameters' => [['name' => 'prefix', 'in' => 'query', 'schema' => ['type' => 'string']]],
                'responses' => ['200' => ['description' => 'Folders and files'], 'default' => $error],
            ],
            'post' => [
                'tags' => ['storage'], 'summary' => 'Upload an object', 'operationId' => 'storage_upload',
                'requestBody' => ['required' => true, 'content' => ['multipart/form-data' => ['schema' => [
                    'type' => 'object',
                    'properties' => [
                        'file' => ['type' => 'string', 'format' => 'binary'],
                        'path' => ['type' => 'string', 'description' => 'Folder inside the bucket'],
                        'name' => ['type' => 'string', 'description' => 'File name (sanitized)'],
                        'upsert' => ['type' => 'boolean'],
                    ],
                    'required' => ['file'],
                ]]]],
                'responses' => ['201' => ['description' => 'Stored object'], 'default' => $error],
            ],
        ];
        $spec['paths']['/storage/{bucket}/{path}'] = [
            'parameters' => [$bucketParam, $pathParam],
            'get' => ['tags' => ['storage'], 'summary' => 'Download an object', 'operationId' => 'storage_download', 'responses' => ['200' => ['description' => 'File'], 'default' => $error]],
            'delete' => ['tags' => ['storage'], 'summary' => 'Delete an object', 'operationId' => 'storage_delete', 'responses' => ['204' => ['description' => 'Deleted'], 'default' => $error]],
        ];
    }

    /**
     * @return array<string, mixed>
     */
    private function columnSchema(Column $column, Resource $resource): array
    {
        $override = $resource->getFieldType($column->name);
        $type = $override['type'] ?? $column->type;
        $schema = match ($type) {
            'integer' => ['type' => 'integer'],
            'number' => ['type' => 'number'],
            'boolean', 'true_false' => ['type' => 'boolean'],
            'date' => ['type' => 'string', 'format' => 'date'],
            'datetime' => ['type' => 'string', 'format' => 'date-time'],
            'time' => ['type' => 'string', 'format' => 'time'],
            'json' => [],
            'uuid' => ['type' => 'string', 'format' => 'uuid'],
            'binary' => ['type' => 'string', 'contentEncoding' => 'base64'],
            'set', 'multiselect' => ['type' => 'array', 'items' => ['type' => 'string']],
            'password' => ['type' => 'string', 'format' => 'password', 'writeOnly' => true],
            default => ['type' => 'string'],
        };
        $enum = in_array($type, ['enum', 'dropdown', 'set', 'multiselect'], true) && is_array($override['extras'] ?? null)
            ? array_map('strval', array_is_list($override['extras']) ? $override['extras'] : array_keys($override['extras']))
            : $column->enumValues;
        if ($enum !== [] && in_array($type, ['enum', 'dropdown', 'string'], true)) {
            $schema['enum'] = $enum;
        }
        if ($column->maxLength !== null && ($schema['type'] ?? null) === 'string' && ! isset($schema['format'])) {
            $schema['maxLength'] = $column->maxLength;
        }
        if ($column->nullable && isset($schema['type']) && is_string($schema['type'])) {
            $schema['type'] = [$schema['type'], 'null'];
        }
        $label = $resource->label($column->name);
        if ($label !== $column->name) {
            $schema['title'] = $label;
        }
        if ($column->comment !== '') {
            $schema['description'] = $column->comment;
        }
        if ($column->primary || in_array($override['type'] ?? null, ['readonly'], true)) {
            $schema['readOnly'] = $column->autoIncrement || ($override['type'] ?? null) === 'readonly';
            if ($schema['readOnly'] === false) {
                unset($schema['readOnly']);
            }
        }

        return $schema;
    }

    /**
     * @return array<string, array<string, mixed>>
     */
    private function commonParameters(): array
    {
        $param = static fn (string $name, string $description, array $schema = ['type' => 'string']): array => [
            'name' => $name, 'in' => 'query', 'required' => false, 'description' => $description, 'schema' => $schema,
        ];

        return [
            'select' => $param('select', 'Columns and embedded relations, e.g. `id,name,offices(city)` or `*,orders(*,orderdetails(*))`'),
            'order' => $param('order', 'Sort, e.g. `lastName.desc,firstName.asc.nullslast`'),
            'limit' => $param('limit', 'Maximum number of rows', ['type' => 'integer', 'minimum' => 0]),
            'offset' => $param('offset', 'Rows to skip', ['type' => 'integer', 'minimum' => 0]),
            'page' => $param('page', 'Page number (alternative to offset)', ['type' => 'integer', 'minimum' => 1]),
            'per_page' => $param('per_page', 'Page size (alternative to limit)', ['type' => 'integer', 'minimum' => 1]),
            'q' => $param('q', 'Search text over the searchable columns'),
            'count' => $param('count', 'Send `exact` to receive the total in Content-Range / X-Total-Count', ['type' => 'string', 'enum' => ['exact']]),
            'format' => $param('format', 'Response format', ['type' => 'string', 'enum' => ['json', 'csv']]),
            'or' => $param('or', 'Logical OR of filters, e.g. `(age.lt.18,age.gt.65)`'),
            'prefer' => ['name' => 'Prefer', 'in' => 'header', 'required' => false, 'schema' => ['type' => 'string'],
                'description' => '`return=minimal|representation`, `resolution=merge-duplicates`, `count=exact`'],
        ];
    }

    private static function schemaName(string $name): string
    {
        return str_replace(' ', '', ucwords(str_replace(['_', '-'], ' ', $name)));
    }
}
